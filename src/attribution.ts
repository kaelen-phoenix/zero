/**
 * What counts as attribution to an AI tool in a commit message or a published
 * text. The factory is engine-agnostic: nothing it commits or publishes names a
 * particular AI, whichever engine worked. A person's co-authorship is kept.
 * Extend the lists here; nothing else decides what is AI attribution.
 */

/** Names and addresses of AI tools, matched as whole words inside a trailer's value or a line. */
export const AI_TOOLS: readonly string[] = [
  "claude", "anthropic", "codex", "openai", "chatgpt", "gpt-?\\d[\\w.-]*", "gemini", "antigravity", "bard",
  "opencode", "copilot", "cursor", "cursoragent", "aider", "devin", "windsurf", "codeium", "amazon q", "jules",
  "noreply@google\\.com", "[\\w.+-]*-noreply@google\\.com", "[\\w.+-]*@anthropic\\.com", "[\\w.+-]*@openai\\.com",
];

const TOOL = `(?:${AI_TOOLS.join("|")})`;

/** Lines that are AI attribution; each is tested against one trimmed line, in any letter case. */
export const ATTRIBUTION_PATTERNS: RegExp[] = [
  // A co-author trailer naming an AI tool, by name or address.
  new RegExp(`^co-authored-by:.*(?<![\\w-])${TOOL}(?![\\w-])`, "i"),
  // A session trailer of an AI tool (Claude-Session, Codex-Session, ...).
  new RegExp(`^${TOOL}[\\w-]*-session:`, "i"),
  // "🤖 Generated with [Claude Code](...)", "Generated by Codex".
  new RegExp(`^\\W*(?:generated|created|made|written|built)\\s+(?:with|by|using)\\b.*(?<![\\w-])${TOOL}(?![\\w-])`, "i"),
  // A bare link to an AI tool's session.
  /^\W*https?:\/\/(?:claude\.ai\/code\/session|chatgpt\.com\/codex\/tasks|jules\.google\.com\/session)\S*$/i,
];

/** Whether a single line is AI attribution. */
export function isAttributionLine(line: string): boolean {
  const text = line.trim();
  return text !== "" && ATTRIBUTION_PATTERNS.some((p) => p.test(text));
}

/**
 * The text without its AI attribution lines. Every other line stays as it was;
 * where lines were removed, no doubled blank line, nor leading or trailing
 * blank line, is left behind. A text without attribution comes back identical.
 */
export function stripAttribution(text: string): string {
  const lines = text.split("\n");
  if (!lines.some(isAttributionLine)) return text;
  const ending = text.endsWith("\n") ? "\n" : "";
  if (ending) lines.pop();
  const blank = (l: string) => l.trim() === "";
  const out: string[] = [];
  let removed = false;
  for (const line of lines) {
    if (isAttributionLine(line)) {
      removed = true;
      continue;
    }
    if (blank(line) && removed && (out.length === 0 || blank(out[out.length - 1]!))) continue;
    if (!blank(line)) removed = false;
    out.push(line);
  }
  if (removed) while (out.length && blank(out[out.length - 1]!)) out.pop();
  return out.join("\n") + ending;
}
